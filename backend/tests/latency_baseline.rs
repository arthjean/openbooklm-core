/// Notebooks seeded per user, and sources and chunks seeded per notebook.
///
/// The lexical measurement is only meaningful if the query matches rows. A
/// search over an empty notebook times query planning against zero tuples, not
/// retrieval, and would make the US-019 regression gate compare noise.
const SEED_NOTEBOOKS: usize = 5;
const SEED_SOURCES: usize = 4;
const SEED_CHUNKS_PER_SOURCE: usize = 40;

/// Vocabulary the seeded chunks are built from. `retrieval` appears in every
/// chunk so the measured query returns a full page of `LIMIT 15` results.
const SEED_SENTENCES: &[&str] = &[
    "Hybrid retrieval fuses dense vector search with lexical ranking.",
    "Reciprocal rank fusion combines retrieval result sets without tuning weights.",
    "The retrieval pipeline reranks candidates before assembling chat context.",
    "Parent chunks preserve retrieval context that child chunks would otherwise lose.",
];

/// Notebook listing and lexical search against a real PostgreSQL instance.
///
/// Ignored by default: the offline suite must stay under two seconds.
#[tokio::test]
#[ignore = "Requires real PostgreSQL database (TEST_DATABASE_URL env var)"]
async fn database_latency_baseline() {
    use openbooklm::core::config::DatabasePoolConfig;
    use openbooklm::repositories::{
        ChunkRepository, GenerationRepository, NotebookRepository, NotebookScope,
        SeaOrmChunkRepository, SeaOrmGenerationRepository, SeaOrmNotebookRepository,
        SeaOrmSearchRepository, SeaOrmSourceRepository, SearchRepository, SourceRepository,
    };
    use openbooklm::services::rag::provenance::{
        ChunkingProvenance, EmbeddingProvenance, GenerationProvenance, Normalization,
    };
    use openbooklm::types::{ChunkMetadata, ChunkWithContext, SourceType};

    let db_url =
        std::env::var("TEST_DATABASE_URL").expect("TEST_DATABASE_URL must be set for this test");
    let db = openbooklm::db::connect(&db_url, &DatabasePoolConfig::default())
        .await
        .expect("Failed to connect to test database");

    let notebooks = SeaOrmNotebookRepository::new(&db);
    let sources = SeaOrmSourceRepository::new(&db);
    let chunks_repo = SeaOrmChunkRepository::new(&db);
    let generations = SeaOrmGenerationRepository::new(&db);
    let search = SeaOrmSearchRepository::new(&db);

    // Seeded chunks reach search only through a published generation (EP-002).
    // The seed therefore goes through the real lifecycle rather than writing
    // rows the active pointer would never reach.
    let seed_provenance = GenerationProvenance {
        embedding: EmbeddingProvenance {
            provider: "latency-baseline".into(),
            model: "zero-vector".into(),
            dimension: openbooklm::core::providers::EMBEDDING_DIM,
            normalization: Normalization::Unknown,
        },
        chunking: ChunkingProvenance::current(1024),
    };

    // Synthetic fixture: one user, a small notebook set, and one notebook
    // populated with indexed content. This is the shape a self-hosted install
    // reaches after ingesting a handful of documents.
    //
    // The account row is required because `notebooks.user_id` references
    // `accounts(id)`. It carries an identifier and two timestamps: no email, no
    // identity subject, nothing a public fixture would have to invent (US-011).
    let user_id = uuid::Uuid::new_v4();
    {
        use openbooklm::entities::account;
        use sea_orm::{ActiveValue::Set, EntityTrait};

        let now = chrono::Utc::now().into();
        account::Entity::insert(account::ActiveModel {
            id: Set(user_id),
            created_at: Set(now),
            updated_at: Set(now),
        })
        .exec(&db)
        .await
        .expect("create synthetic account");
    }

    let mut created = Vec::new();
    for i in 0..SEED_NOTEBOOKS {
        created.push(
            notebooks
                .create(user_id, format!("Baseline notebook {i}"), None)
                .await
                .expect("create notebook"),
        );
    }
    let notebook_id = created[0].id;

    let mut seeded_chunks = 0usize;
    for s in 0..SEED_SOURCES {
        let source = sources
            .create(
                notebook_id,
                format!("Baseline source {s}"),
                SourceType::Text,
                SEED_SENTENCES.join(" "),
                None,
            )
            .await
            .expect("create source");

        let chunks: Vec<ChunkWithContext> = (0..SEED_CHUNKS_PER_SOURCE)
            .map(|c| {
                let sentence = SEED_SENTENCES[c % SEED_SENTENCES.len()];
                ChunkWithContext {
                    content: format!("{sentence} Passage {c} of baseline source {s}."),
                    context_prefix: None,
                    parent_content: None,
                    metadata: ChunkMetadata {
                        position: u32::try_from(c).unwrap_or(0),
                        ..Default::default()
                    },
                    content_hash: String::new(),
                }
            })
            .collect();
        // Zero vectors: this measurement is lexical, and the embedding values do
        // not affect the tsvector path. Dimension must still match the schema.
        let embeddings: Vec<Vec<f32>> = vec![vec![0.0; 1024]; chunks.len()];

        let generation_id = generations
            .claim(source.id, &seed_provenance)
            .await
            .expect("claim generation")
            .expect("a fresh source has no competing build");
        chunks_repo
            .store_chunks(generation_id, source.id, &chunks, &embeddings)
            .await
            .expect("store chunks");
        generations
            .record_build_plan(
                generation_id,
                i32::try_from(chunks.len()).expect("seed size fits in i32"),
                &seed_provenance.chunking,
            )
            .await
            .expect("record build plan");
        let _published = generations
            .publish(
                generation_id,
                source.id,
                openbooklm::core::providers::EMBEDDING_DIM,
            )
            .await
            .expect("publish generation");
        seeded_chunks += chunks.len();
    }

    // Fail loudly rather than record a meaningless number: a lexical baseline
    // over an empty result set is not a baseline.
    let hits = search
        .search_lexical_chunks(NotebookScope::new(user_id, notebook_id), "retrieval", 15)
        .await
        .expect("lexical search");
    assert!(
        !hits.is_empty(),
        "seeded {seeded_chunks} chunks but lexical search returned none; \
         the tsvector index or the seed vocabulary is wrong, and the measurement \
         below would be meaningless"
    );
    println!(
        "seeded {seeded_chunks} chunks across {SEED_SOURCES} sources; \
         lexical query returns {} rows",
        hits.len()
    );

    let listing = measure_async("notebook_listing", || async {
        notebooks
            .list_with_source_counts(user_id)
            .await
            .expect("list notebooks");
    })
    .await;

    let lexical = measure_async("lexical_search", || async {
        search
            .search_lexical_chunks(NotebookScope::new(user_id, notebook_id), "retrieval", 15)
            .await
            .expect("lexical search");
    })
    .await;

    // Deleting the account cascades to notebooks, sources and chunks, so the
    // measurement leaves no rows behind.
    {
        use openbooklm::entities::account;
        use sea_orm::EntityTrait;

        account::Entity::delete_by_id(user_id)
            .exec(&db)
            .await
            .expect("cleanup synthetic account");
    }

    println!("\n-- database latency baseline --");
    persist("database.json", &[listing, lexical]);
}

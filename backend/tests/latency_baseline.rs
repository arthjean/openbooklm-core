//! Latency baseline harness (US-002, EP-001).
//!
//! Records P50 and P95 for the four operations the PRD names as the regression
//! guard for the open-core cutover (US-019 allows at most a 10% P95 regression
//! against these numbers).
//!
//! Two of the four run offline and are part of the default suite. The two that
//! touch PostgreSQL are `#[ignore]`, following the repository rule that the
//! default `cargo test` stays under two seconds with no external service.
//!
//! ```bash
//! # offline measurements
//! cargo test --test latency_baseline -- --nocapture
//!
//! # database-backed measurements
//! TEST_DATABASE_URL=postgres://... cargo test --test latency_baseline -- --ignored --nocapture
//!
//! # persist a machine-readable report
//! UPDATE_BASELINE=1 cargo test --test latency_baseline -- --nocapture
//! ```
//!
//! **Nothing here asserts a wall-clock threshold.** Absolute timings are
//! machine-dependent; a test that fails on a slow CI runner teaches people to
//! ignore it. The harness produces measurements, and
//! `docs/contracts/latency-baseline.md` records the numbers taken on the
//! reference environment. Comparison against those numbers is a deployment gate
//! (US-019), not a unit test.

#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

use serde_json::json;

/// Warm-up iterations discarded before measuring.
const WARMUP: usize = 20;
/// Measured iterations per operation.
const SAMPLES: usize = 200;

// ============================================================================
// Measurement
// ============================================================================

#[derive(Debug)]
struct Measurement {
    operation: &'static str,
    samples: Vec<Duration>,
}

impl Measurement {
    fn percentile(&self, p: f64) -> Duration {
        let mut sorted = self.samples.clone();
        sorted.sort_unstable();
        // Nearest-rank: the smallest value at or above the p-th percentile.
        let rank = ((p / 100.0) * sorted.len() as f64).ceil().max(1.0) as usize;
        sorted[rank.min(sorted.len()) - 1]
    }

    fn report(&self) -> serde_json::Value {
        // Nanoseconds, not microseconds: the offline operations run in well under
        // 1 µs in release, and a microsecond field records them as 0.
        json!({
            "operation": self.operation,
            "samples": self.samples.len(),
            "p50_ns": u64::try_from(self.percentile(50.0).as_nanos()).unwrap_or(u64::MAX),
            "p95_ns": u64::try_from(self.percentile(95.0).as_nanos()).unwrap_or(u64::MAX),
        })
    }

    fn print(&self) {
        println!(
            "{:<34} n={:<4} p50={:>12.3} µs  p95={:>12.3} µs",
            self.operation,
            self.samples.len(),
            self.percentile(50.0).as_secs_f64() * 1_000_000.0,
            self.percentile(95.0).as_secs_f64() * 1_000_000.0,
        );
    }
}

fn measure<F: FnMut()>(operation: &'static str, mut op: F) -> Measurement {
    for _ in 0..WARMUP {
        op();
    }
    let mut samples = Vec::with_capacity(SAMPLES);
    for _ in 0..SAMPLES {
        let start = Instant::now();
        op();
        samples.push(start.elapsed());
    }
    Measurement { operation, samples }
}

async fn measure_async<F, Fut>(operation: &'static str, mut op: F) -> Measurement
where
    F: FnMut() -> Fut,
    Fut: std::future::Future<Output = ()>,
{
    for _ in 0..WARMUP {
        op().await;
    }
    let mut samples = Vec::with_capacity(SAMPLES);
    for _ in 0..SAMPLES {
        let start = Instant::now();
        op().await;
        samples.push(start.elapsed());
    }
    Measurement { operation, samples }
}

fn report_path(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .join("contracts/baseline/latency")
        .join(name)
}

fn persist(name: &str, measurements: &[Measurement]) {
    for m in measurements {
        m.print();
    }
    if std::env::var("UPDATE_BASELINE").is_ok_and(|v| v != "0" && !v.is_empty()) {
        let path = report_path(name);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        let body = json!({
            "note": "Machine-dependent. Regenerated by cargo test --test latency_baseline.",
            "measurements": measurements.iter().map(Measurement::report).collect::<Vec<_>>(),
        });
        let mut rendered = serde_json::to_string_pretty(&body).unwrap();
        rendered.push('\n');
        std::fs::write(&path, rendered).unwrap();
        println!("wrote {}", path.display());
    }
}

// ============================================================================
// Offline operations
// ============================================================================

/// Source creation validation and time to first chat token.
///
/// Time to first token is measured against `FakeLlmProvider`-equivalent frames,
/// so it captures the pipeline's own overhead — stream construction, SSE
/// framing, parse — with the provider's network latency removed. That is the
/// part the open-core split can regress.
#[tokio::test]
async fn offline_latency_baseline() {
    use futures::StreamExt;
    use openbooklm::llm::{LlmStreamEvent, parse_openai_sse_data};
    use openbooklm::validation::{validate_content, validate_title, validate_url_for_ssrf};

    let title = "A representative source title";
    let content = "Synthetic source body. ".repeat(200);

    let validation = measure("source_creation_validation", || {
        validate_title(title).unwrap();
        validate_content(&content).unwrap();
        validate_url_for_ssrf("https://example.com/article").unwrap();
    });

    let first_token = measure_async("chat_time_to_first_token", || async {
        let frames: Vec<&'static str> = vec![
            "data: {\"choices\":[{\"delta\":{\"content\":\"It \"},\"index\":0}]}\n\n",
            "data: {\"choices\":[{\"delta\":{\"content\":\"says\"},\"index\":0}]}\n\n",
            "data: [DONE]\n\n",
        ];
        let mut stream = futures::stream::iter(frames);
        while let Some(frame) = stream.next().await {
            for line in frame.lines() {
                if let Some(data) = line.strip_prefix("data: ")
                    && let Some(LlmStreamEvent::TextDelta { .. }) = parse_openai_sse_data(data)
                {
                    return; // stop at the first token, which is what we measure
                }
            }
        }
        unreachable!("the synthetic stream always yields a text delta");
    })
    .await;

    assert_eq!(validation.samples.len(), SAMPLES);
    assert_eq!(first_token.samples.len(), SAMPLES);

    println!("\n-- offline latency baseline --");
    persist("offline.json", &[validation, first_token]);
}

